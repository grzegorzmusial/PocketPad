package pl.pocketpad;

/** Standard HID gamepad: 16 buttons, 8-way hat, X/Y/Z/Rz. */
public final class PadState {
    public static final byte REPORT_ID = 1;
    public static final byte[] DESCRIPTOR = new byte[] {
        0x05,0x01,0x09,0x05,(byte)0xA1,0x01,(byte)0x85,0x01,
        0x05,0x09,0x19,0x01,0x29,0x10,0x15,0x00,0x25,0x01,0x75,0x01,(byte)0x95,0x10,(byte)0x81,0x02,
        0x05,0x01,0x09,0x39,0x15,0x00,0x25,0x07,0x35,0x00,0x46,0x3B,0x01,0x65,0x14,
        0x75,0x04,(byte)0x95,0x01,(byte)0x81,0x42,0x65,0x00,
        0x75,0x04,(byte)0x95,0x01,(byte)0x81,0x03,
        0x09,0x30,0x09,0x31,0x09,0x32,0x09,0x35,
        0x15,(byte)0x81,0x25,0x7F,0x35,(byte)0x81,0x45,0x7F,
        0x75,0x08,(byte)0x95,0x04,(byte)0x81,0x02,(byte)0xC0
    };
    public int buttons, hat=8;
    public int lx,ly,rx,ry;
    public byte[] report() { return new byte[]{(byte)buttons,(byte)(buttons>>8),(byte)hat,(byte)lx,(byte)ly,(byte)rx,(byte)ry}; }
    public void clear() { buttons=0;hat=8;lx=ly=rx=ry=0; }
    public static int axis(float v) { return Math.round(Math.max(-1,Math.min(1,v))*127); }
    public static int hat(float x,float y) {
        if(Math.hypot(x,y)<.30) return 8;
        return ((int)Math.round(Math.atan2(x,-y)/(Math.PI/4))+8)%8;
    }
}
